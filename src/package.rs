const PACK_PLUGIN_FILE: &str = "_pack.vim";
const PLUGIN_HEADER: &str = "\" Generated by pack. DO NOT EDIT!

scriptencoding utf-8

function! s:do_cmd(cmd, bang, start, end, args)
    exec printf('%s%s%s %s', (a:start == a:end ? '' : (a:start.','.a:end)), a:cmd, a:bang, a:args)
endfunction

function! s:load_on_map(mode, keys, repos)
    for repo in a:repos
        exec 'packadd! ' . repo
    endfor
    exec a:mode . 'unmap ' . a:keys
    call feedkeys(a:keys, 'i')
endfunction
";

const PACKFILE_HEADER: &[u8] = b"# vim: ft=yaml
#
# Generated by pack.

";

static BASE_DIR: OnceLock<PathBuf> = OnceLock::new();
static PACK_DIR: OnceLock<PathBuf> = OnceLock::new();
static PACK_CONFIG_DIR: OnceLock<PathBuf> = OnceLock::new();
static PACK_FILE: OnceLock<PathBuf> = OnceLock::new();
static PACK_PLUGIN_DIR: OnceLock<PathBuf> = OnceLock::new();

fn base_dir() -> &'static PathBuf {
    BASE_DIR.get_or_init(|| {
        env::var("VIM_CONFIG_PATH")
            .map(PathBuf::from)
            .unwrap_or_else(|_| {
                let home = dirs::home_dir().expect("No home directory found");
                home.join(".vim")
            })
    })
}

fn pack_dir() -> &'static PathBuf {
    PACK_DIR.get_or_init(|| base_dir().join("pack"))
}

fn pack_config_dir() -> &'static PathBuf {
    PACK_CONFIG_DIR.get_or_init(|| base_dir().join(".pack"))
}

fn pack_file() -> &'static PathBuf {
    PACK_FILE.get_or_init(|| pack_config_dir().join("packfile"))
}

fn pack_plugin_dir() -> &'static PathBuf {
    PACK_PLUGIN_DIR.get_or_init(|| base_dir().join("plugin"))
}

#[derive(Debug, Clone)]
pub struct Package {
    pub name: String,
    pub category: String,
    pub opt: bool,
    /// Load this package on this command
    pub load_command: Option<String>,
    /// Load this package for these types
    pub for_types: Vec<String>,
    /// Build command for this package
    pub build_command: Option<String>,
    /// Repositories this package requires loaded first (issue #56)
    pub depend: Vec<String>,
    /// Load this package when these mappings are triggered (issue #49)
    pub on_map: Vec<String>,
    /// Local plugin
    pub local: bool,
}

impl Package {
    pub fn new(name: &str, category: &str, opt: bool) -> Package {
        Package {
            name: name.to_string(),
            category: category.to_string(),
            opt,
            load_command: None,
            for_types: Vec::new(),
            build_command: None,
            depend: Vec::new(),
            on_map: Vec::new(),
            local: false,
        }
    }

    pub fn is_installed(&self) -> bool {
        self.path().is_dir()
    }

    pub fn set_category<T: Into<String>>(&mut self, cat: T) {
        self.category = cat.into();
    }

    pub fn set_opt(&mut self, opt: bool) {
        self.opt = opt;
    }

    pub fn set_load_command(&mut self, cmd: &str) {
        self.load_command = Some(cmd.to_string())
    }

    pub fn set_types(&mut self, types: Vec<String>) {
        self.for_types = types
    }

    pub fn set_build_command(&mut self, cmd: &str) {
        self.build_command = Some(cmd.to_string())
    }

    pub fn set_depend(&mut self, depend: Vec<String>) {
        self.depend = depend
    }

    pub fn set_on_map(&mut self, on_map: Vec<String>) {
        self.on_map = on_map
    }

    pub fn from_yaml(doc: &Yaml) -> Result<Package> {
        let name = doc["name"]
            .as_str()
            .map(|s| s.to_string())
            .ok_or(Error::Format)?;
        let opt = doc["opt"].as_bool().ok_or(Error::Format)?;
        let category = doc["category"]
            .as_str()
            .map(|s| s.to_string())
            .ok_or(Error::Format)?;
        let cmd = doc["on"].as_str().map(|s| s.to_string());
        let build = doc["build"].as_str().map(|s| s.to_string());
        let is_local = doc["local"].as_bool().unwrap_or(false);

        let on_map = match doc["on_map"].as_vec() {
            Some(d) => {
                let mut on_map = Vec::with_capacity(d.len());
                for e in d {
                    on_map.push(e.as_str().map(|s| s.to_string()).ok_or(Error::Format)?);
                }
                on_map
            }
            None => vec![],
        };

        let depend = match doc["depend"].as_vec() {
            Some(d) => {
                let mut depend = Vec::with_capacity(d.len());
                for e in d {
                    depend.push(e.as_str().map(|s| s.to_string()).ok_or(Error::Format)?);
                }
                depend
            }
            None => vec![],
        };

        let types = match doc["for"].as_vec() {
            Some(f) => {
                let mut types = Vec::with_capacity(f.len());
                for e in f {
                    types.push(e.as_str().map(|s| s.to_string()).ok_or(Error::Format)?);
                }
                types
            }
            None => vec![],
        };

        Ok(Package {
            name,
            category,
            opt,
            load_command: cmd,
            for_types: types,
            build_command: build,
            depend,
            on_map,
            local: is_local,
        })
    }

    pub fn into_yaml(self) -> Yaml {
        let mut doc = Hash::new();
        doc.insert(Yaml::from_str("name"), Yaml::from_str(&self.name));
        doc.insert(Yaml::from_str("category"), Yaml::from_str(&self.category));
        doc.insert(Yaml::from_str("opt"), Yaml::Boolean(self.opt));
        doc.insert(Yaml::from_str("local"), Yaml::Boolean(self.local));
        if let Some(ref c) = self.load_command {
            doc.insert(Yaml::from_str("on"), Yaml::from_str(c));
        }
        if let Some(ref c) = self.build_command {
            doc.insert(Yaml::from_str("build"), Yaml::from_str(c));
        }
        if !self.for_types.is_empty() {
            let types = self
                .for_types
                .iter()
                .map(|e| Yaml::from_str(e))
                .collect::<Vec<Yaml>>();
            doc.insert(Yaml::from_str("for"), Yaml::Array(types));
        }
        if !self.depend.is_empty() {
            let depend = self
                .depend
                .iter()
                .map(|e| Yaml::from_str(e))
                .collect::<Vec<Yaml>>();
            doc.insert(Yaml::from_str("depend"), Yaml::Array(depend));
        }
        if !self.on_map.is_empty() {
            let on_map = self
                .on_map
                .iter()
                .map(|e| Yaml::from_str(e))
                .collect::<Vec<Yaml>>();
            doc.insert(Yaml::from_str("on_map"), Yaml::Array(on_map));
        }
        Yaml::Hash(doc)
    }

    #[inline]
    fn basename(&self) -> &str {
        Path::new(&self.name)
            .file_name()
            .iter()
            .filter_map(|e| e.to_str())
            .next()
            .unwrap_or("")
    }

    pub fn path(&self) -> PathBuf {
        let repo = if self.local {
            self.basename()
        } else {
            let (_, repo) = self.repo();
            repo
        };
        if self.opt {
            pack_dir().join(&self.category).join("opt").join(repo)
        } else {
            pack_dir().join(&self.category).join("start").join(repo)
        }
    }

    pub fn config_path(&self) -> PathBuf {
        // Issue #22: appending `.vim` only when the escaped name lacks it
        // collides — `junegunn/fzf` and `junegunn/fzf.vim` both map to
        // `junegunn-fzf.vim` and share one configuration file (and one
        // inlined copy in `_pack.vim`). Always appending `.pack` after the
        // full escaped name keeps the two distinct.
        let name = if self.local {
            self.basename().to_string()
        } else {
            self.name.replace("/", "-")
        };
        pack_config_dir().join(format!("{}.pack", name))
    }

    /// The pre-#22 configuration name (escaped name, `.vim` appended when
    /// missing). Kept so configurations written by older pack versions can
    /// still be found, read and deleted.
    pub fn legacy_config_path(&self) -> PathBuf {
        let name = if self.local {
            self.basename().to_string()
        } else {
            self.name.replace("/", "-")
        };
        let fname = if name.ends_with(".vim") {
            name
        } else {
            format!("{}.vim", &name)
        };
        pack_config_dir().join(fname)
    }

    /// Resolve this package's configuration file: the canonical name when it
    /// exists (or when nothing exists yet), the legacy name when only that
    /// exists. Configurations from before #22 keep working until rewritten.
    pub fn existing_config_path(&self) -> PathBuf {
        let canonical = self.config_path();
        if canonical.is_file() {
            return canonical;
        }
        let legacy = self.legacy_config_path();
        if legacy.is_file() {
            return legacy;
        }
        canonical
    }

    pub fn repo(&self) -> (&str, &str) {
        let mut info: Vec<&str> = self.name.splitn(2, '/').collect();
        info.reverse();

        let repo = info.iter().next().unwrap_or(&"");
        let user = info.iter().next().unwrap_or(&"");

        (user, repo)
    }

    pub fn try_build(&self) -> Result<()> {
        if let Some(ref c) = self.build_command {
            let path = self.path();
            let p = process::Command::new("sh")
                .arg("-c")
                .arg(c)
                .stdout(process::Stdio::piped())
                .stderr(process::Stdio::piped())
                .current_dir(&path)
                .spawn()?;
            let output = p.wait_with_output()?;
            if !output.status.success() {
                let err = String::from_utf8(output.stderr)
                    .unwrap_or_else(|_| String::from("No error output!"));
                return Err(Error::Build(err));
            }
        }
        Ok(())
    }
}

impl fmt::Display for Package {
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        let name = if self.opt { "opt" } else { "start" };
        let on = match self.load_command {
            Some(ref c) => format!(" [Load on `{}`]", c),
            None => "".to_string(),
        };

        let types = if !self.for_types.is_empty() {
            let types = self.for_types.join(",");
            format!(" [For {}]", types)
        } else {
            "".to_string()
        };
        write!(
            f,
            "{} => pack/{}/{}{}{}",
            &self.name, &self.category, name, on, types
        )
    }
}

pub fn fetch() -> Result<Vec<Package>> {
    if pack_file().is_file() {
        fetch_from_packfile(pack_file())
            .map_err(|e| Error::PackFile(format!("Fail to parse packfile: {}", e)))
    } else {
        Ok(vec![])
    }
}

fn fetch_from_packfile<P: AsRef<Path>>(packfile: P) -> Result<Vec<Package>> {
    let mut data = String::new();
    File::open(packfile.as_ref())?.read_to_string(&mut data)?;
    let docs = YamlLoader::load_from_str(&data)?;

    let mut ret = Vec::new();
    if !docs.is_empty() {
        if let Some(doc) = docs[0].as_vec() {
            for d in doc {
                ret.push(Package::from_yaml(d)?);
            }
        }
    }
    Ok(ret)
}

pub fn save(packs: Vec<Package>) -> Result<()> {
    let packs = packs
        .into_iter()
        .map(|e| e.into_yaml())
        .collect::<Vec<Yaml>>();
    let doc = Yaml::Array(packs);
    let mut out = String::new();
    {
        let mut emitter = YamlEmitter::new(&mut out);
        emitter.dump(&doc)?;
    }
    if !pack_config_dir().is_dir() {
        fs::create_dir_all(pack_config_dir())?;
    }
    let mut f = File::create(pack_file())?;
    f.write_all(PACKFILE_HEADER)?;
    f.write_all(out.as_bytes())?;
    Ok(())
}

/// Transitively resolve `p`'s load dependencies (issue #56): every
/// repository that must be loaded before `p`, in load order, excluding
/// `p` itself. Unknown dependencies (not managed by pack) are an error —
/// a silent skip would emit a trigger that loads nothing.
fn resolve_depend(p: &Package, packs: &[Package]) -> Result<Vec<String>> {
    let mut out = Vec::new();
    let mut stack = vec![p.name.clone()];
    while let Some(name) = stack.pop() {
        for dep in &packs
            .iter()
            .find(|x| x.name == name)
            .ok_or_else(|| Error::PackFile(format!("Unknown dependency: {}", name)))?
            .depend
        {
            if !out.contains(dep) {
                out.push(dep.clone());
            }
            stack.push(dep.clone());
        }
    }
    // Resolve to repository names: the generated triggers packadd those.
    Ok(out
        .iter()
        .map(|name| {
            packs
                .iter()
                .find(|x| x.name == *name)
                .map(|x| x.repo().1.to_string())
                .unwrap_or_else(|| name.clone())
        })
        .collect())
}

pub fn update_pack_plugin(packs: &[Package]) -> Result<()> {
    if !pack_plugin_dir().is_dir() {
        fs::create_dir_all(pack_plugin_dir())?;
    }

    let mut f = File::create(pack_plugin_dir().join(PACK_PLUGIN_FILE))?;
    f.write_all(format!("{}\n\n", PLUGIN_HEADER).as_bytes())?;

    let mut buf = String::new();
    for (p, path) in packs.iter().map(|x| (x, x.existing_config_path())) {
        buf.clear();
        let mut written = false;
        // Issue #56: load dependencies first, in the same trigger.
        let deps = resolve_depend(p, packs)?;
        let deps_prefix = if deps.is_empty() {
            String::new()
        } else {
            let mut s = String::new();
            for dep in &deps {
                s.push_str(&format!("packadd {} | ", dep));
            }
            s
        };

        if let Some(ref c) = p.load_command {
            f.write_all(format!("\" {}\n", &p.name).as_bytes())?;
            written = true;
            let (_, repo) = p.repo();
            let msg = format!(
                "command! -nargs=* -range -bang {cmd} {deps}packadd {repo} | \
                 call s:do_cmd('{cmd}', \"<bang>\", <line1>, <line2>, <q-args>)\n\n",
                cmd = c,
                deps = deps_prefix,
                repo = repo
            );
            f.write_all(msg.as_bytes())?;
        }

        if !p.for_types.is_empty() {
            if !written {
                f.write_all(format!("\" {}\n", &p.name).as_bytes())?;
                written = true;
            }
            let (_, repo) = p.repo();
            let msg = format!(
                "autocmd FileType {types} {deps}packadd {repo}\n\n",
                types = p.for_types.join(","),
                deps = deps_prefix,
                repo = repo,
            );
            f.write_all(msg.as_bytes())?;
        }

        if !p.on_map.is_empty() {
            if !written {
                f.write_all(format!("\" {}\n", &p.name).as_bytes())?;
                written = true;
            }
            // Issue #49: a bootstrap mapping per key: load the dependency
            // chain (see resolve_depend), drop the bootstrap, re-trigger
            // the key so the plugin's own mapping fires.
            let (_, repo) = p.repo();
            let mut repos = deps.clone();
            repos.push(repo.to_string());
            let repos = format!("['{}']", repos.join("', '"));
            for map in &p.on_map {
                for mode in ["n", "x", "o"] {
                    f.write_all(
                        format!(
                            "{mode}noremap <silent> {map} \
                             <Cmd>call s:load_on_map('{mode}', '{map}', {repos})<CR>\n",
                            mode = mode,
                            map = map,
                            repos = repos,
                        )
                        .as_bytes(),
                    )?;
                }
            }
            f.write_all(b"\n")?;
        }

        if path.is_file() {
            File::open(&path)?.read_to_string(&mut buf)?;
            if !written {
                f.write_all(format!("\" {}\n", &p.name).as_bytes())?;
            }
            f.write_all(format!("{}\n", &buf).as_bytes())?;
        }
    }
    Ok(())
}

fn read_dir<H>(dir: &Path, mut action: H) -> Result<()>
where
    H: FnMut(&Path, String) -> Result<()>,
{
    if !dir.is_dir() {
        return Ok(());
    }
    for entry in dir.read_dir()? {
        if let Ok(e) = entry {
            let sub = e.path();
            let item = match sub.file_name().iter().flat_map(|s| s.to_str()).next() {
                None => continue,
                Some(i) => i.to_string(),
            };
            if sub.is_dir() && !item.starts_with('.') {
                action(&sub, item)?;
            }
        }
    }
    Ok(())
}

pub fn walk_packs<F>(category: &Option<String>, start: bool, opt: bool, callback: F) -> Result<()>
where
    F: Fn(&str, &str, &str),
{
    read_dir(pack_dir(), |path, cate| {
        let is_match = category.as_ref().map_or(true, |c| *c == cate);
        if !is_match {
            Ok(())
        } else {
            read_dir(path, |subpath, option| {
                if (start && option != "start")
                    || (opt && option != "opt")
                    || (option != "start" && option != "opt")
                {
                    Ok(())
                } else {
                    read_dir(subpath, |_, name| {
                        callback(&cate, &option, &name);
                        Ok(())
                    })
                }
            })
        }
    })?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn package_path_user_repo() {
        let p = Package::new("user/reponame", "", false);
        let exp = pack_dir().join("start").join("reponame");
        assert_eq!(exp, p.path());
    }

    #[test]
    fn package_path_nouser() {
        let p = Package::new("reponame", "", false);
        let exp = pack_dir().join("start").join("reponame");
        assert_eq!(exp, p.path());
    }

    #[test]
    fn config_path_distinguishes_vim_suffix() {
        // Issue #22: `fzf` and `fzf.vim` must not share a config file.
        let a = Package::new("junegunn/fzf", "", false).config_path();
        let b = Package::new("junegunn/fzf.vim", "", false).config_path();
        assert_ne!(a, b);
        assert!(a.ends_with("junegunn-fzf.pack"));
        assert!(b.ends_with("junegunn-fzf.vim.pack"));
    }

    #[test]
    fn package_path_repo_slash() {
        let p = Package::new("user/reponame/with_slash", "", false);
        let exp = pack_dir().join("start").join("reponame/with_slash");
        assert_eq!(exp, p.path());
    }
}
